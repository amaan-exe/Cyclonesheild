"""
Cyclone Horizon — QC Report Generator
Auto-generates a Markdown QC report per pipeline run.
"""

from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional

import pandas as pd

from src.utils.io import ensure_dir
from src.utils.logging_config import get_logger

logger = get_logger("validation.qc_report")


def generate_qc_report(
    qc_summary: Dict,
    df: pd.DataFrame,
    output_dir: str = "outputs/reports",
    run_id: str = "",
) -> str:
    """
    Generate a Markdown QC report summarizing data quality.
    
    Parameters
    ----------
    qc_summary : dict from run_all_track_checks()
    df : the validated DataFrame
    output_dir : where to write the report
    run_id : pipeline run identifier
    
    Returns
    -------
    str : path to the generated report
    """
    ensure_dir(output_dir)
    report_path = str(Path(output_dir) / f"qc_report_{run_id or 'latest'}.md")
    
    # Category distribution
    cat_counts = ""
    if "imd_category_name" in df.columns:
        counts = df.groupby("imd_category_name")["storm_id"].nunique()
        for cat, count in counts.items():
            cat_counts += f"| {cat} | {count} |\n"
    
    # Storm completeness
    storm_stats = ""
    if "storm_id" in df.columns and "timestamp" in df.columns:
        for sid, group in df.groupby("storm_id"):
            n_fixes = len(group)
            duration_h = (group["timestamp"].max() - group["timestamp"].min()).total_seconds() / 3600
            expected = max(1, duration_h / 3)  # 3-hourly fixes
            completeness = min(100, n_fixes / expected * 100)
            name = group["name"].iloc[0] if "name" in group.columns else sid
            if completeness < 60:
                storm_stats += f"| {sid} | {name} | {n_fixes} | {duration_h:.0f}h | {completeness:.0f}% | ⚠️ LOW |\n"
    
    report = f"""# Cyclone Horizon — Data Quality Report
**Generated**: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}  
**Run ID**: `{run_id}`

---

## Summary

| Metric | Value |
|--------|-------|
| Total Records | {qc_summary.get('total_records', 'N/A')} |
| Total Storms | {qc_summary.get('total_storms', 'N/A')} |
| Records with Wind Data | {qc_summary.get('records_with_wind', 'N/A')} |
| Records with Pressure Data | {qc_summary.get('records_with_pressure', 'N/A')} |

## QC Check Results

| Check | Failures |
|-------|----------|
| Wind out of bounds | {qc_summary.get('wind_out_of_bounds', 0)} |
| Pressure out of bounds | {qc_summary.get('pressure_out_of_bounds', 0)} |
| Outside basin bounds | {qc_summary.get('outside_basin', 0)} |
| Temporal flags | {qc_summary.get('temporal_flags', 0)} |

## IMD Category Distribution (by storm count)

| Category | Storm Count |
|----------|-------------|
{cat_counts}

## Low-Completeness Storms (< 60% expected fixes)

| Storm ID | Name | Fixes | Duration | Completeness | Status |
|----------|------|-------|----------|--------------|--------|
{storm_stats if storm_stats else "| — | All storms pass completeness check | — | — | — | ✅ |"}

---

*Report generated by Cyclone Horizon QC Pipeline*
"""
    
    with open(report_path, "w", encoding="utf-8") as f:
        f.write(report)
    
    logger.info(f"QC report written to {report_path}")
    return report_path
